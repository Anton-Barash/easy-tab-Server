-- ============================================================
-- Миграция 003: Связь файлов с отчётами
--
-- Добавляет:
--   - files.report_id — связь файла с отчётом (FK)
--   - reports.ks3_folder — путь к папке отчёта в KS3
--
-- Это позволяет:
--   1. Получать список файлов отчёта одним SQL-запросом
--   2. Управлять доступом на уровне отчёта
--   3. Удалять отчёт полностью (папка KS3 + записи в БД)
--   4. Считать размер отчёта через SUM(files.size)
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. Добавляем ks3_folder в таблицу reports
--    Хранит путь к папке отчёта в KS3, например: "reports/abc-123/"
--    Все файлы отчёта лежат внутри этой папки.
--    Может быть NULL для старых отчётов (где хранился только JSON).
-- ------------------------------------------------------------
ALTER TABLE reports
    ADD COLUMN IF NOT EXISTS ks3_folder TEXT;

COMMENT ON COLUMN reports.ks3_folder IS 'Путь к папке отчёта в KS3 (например: reports/uuid/). NULL для старых отчётов.';

-- ------------------------------------------------------------
-- 2. Добавляем report_id в таблицу files
--    Связывает файл с отчётом. Может быть NULL для файлов,
--    не привязанных к конкретному отчёту (например, загруженных
--    через общий эндпоинт /files/upload).
-- ------------------------------------------------------------
ALTER TABLE files
    ADD COLUMN IF NOT EXISTS report_id BIGINT REFERENCES reports(id) ON DELETE CASCADE;

COMMENT ON COLUMN files.report_id IS 'Отчёт, к которому привязан файл (NULL = самостоятельный файл)';

-- ------------------------------------------------------------
-- 3. Индекс для быстрого поиска файлов отчёта
--    Запрос: SELECT * FROM files WHERE report_id = $1
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_files_report ON files(report_id);

-- ------------------------------------------------------------
-- 4. Индекс для поиска по storage_key (для удаления папки)
--    Позволяет быстро найти файлы по префиксу KS3-ключа
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_files_storage_key ON files(storage_key);

COMMIT;
